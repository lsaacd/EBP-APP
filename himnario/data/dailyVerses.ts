export type DailyVerse = (typeof DAILY_VERSES)[number];
export function getDailyVerse(date = new Date()) {
  const dayIndex =
    (date.getFullYear() * 1000 + date.getMonth() * 100 + date.getDate()) %
    DAILY_VERSES.length;
  return { dayIndex, verse: DAILY_VERSES[dayIndex] };
}
