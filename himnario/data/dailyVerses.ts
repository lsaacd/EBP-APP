export type DailyVerse = (typeof DAILY_VERSES)[number];
/**
 * Consecutive integer day number for the user's local calendar date.
 * Using Date.UTC(y, m, d) avoids DST 23h/25h drift and advances by exactly +1
 * across every month boundary and leap year.
 */
export function getLocalDayNumber(date = new Date()): number {
  return Math.floor(
    Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86_400_000,
  );
}
export function getDailyVerse(date = new Date()) {
  const dayNumber = getLocalDayNumber(date);
  const len = DAILY_VERSES.length;
  const dayIndex = ((dayNumber % len) + len) % len;
  return { dayIndex, verse: DAILY_VERSES[dayIndex] };
}
