export const translateCategory = (cat: string, lang: Language): string => {
  if (!cat) return '';
  if (lang === 'es') return cat;
  const trimmed = cat.trim();
  return categoryTranslations[trimmed] || trimmed;
};

export const translateCategories = (categoriesStr: string, lang: Language): string => {
  if (!categoriesStr) return '';
  const parts = categoriesStr.split('•').map(c => c.trim()).filter(Boolean);
  if (lang === 'es') return parts.join('  ·  ');
  return parts.map(c => translateCategory(c, 'en')).join('  ·  ');
};

export type Strings = typeof strings.es;

interface LanguageContextType {
  language: Language;
  hymnLanguage: Language;
  t: Strings;
  setLanguage: (lang: Language) => void;
  setHymnLanguage: (lang: Language) => void;
}

const LanguageContext = createContext<LanguageContextType>({
  language: 'es',
  hymnLanguage: 'es',
  t: strings.es,
  setLanguage: () => { },
  setHymnLanguage: () => { },
});

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>('es');
  const [hymnLanguage, setHymnLanguageState] = useState<Language>('es');
  const uiMutatedRef = React.useRef(false);
  const hymnMutatedRef = React.useRef(false);

  useEffect(() => {
    AsyncStorage.multiGet([STORAGE_KEY, HYMN_LANGUAGE_STORAGE_KEY])
      .then((entries) => {
        const uiRaw = entries[0]?.[1];
        const hymnRaw = entries[1]?.[1];
        if (!uiMutatedRef.current && (uiRaw === 'en' || uiRaw === 'es')) setLanguageState(uiRaw);
        if (!hymnMutatedRef.current && (hymnRaw === 'en' || hymnRaw === 'es')) setHymnLanguageState(hymnRaw);
      })
      .catch(() => {});
  }, []);

  const setLanguage = useCallback((lang: Language) => {
    uiMutatedRef.current = true;
    setLanguageState(lang);
    AsyncStorage.setItem(STORAGE_KEY, lang).catch(() => {});
  }, []);

  const setHymnLanguage = useCallback((lang: Language) => {
    hymnMutatedRef.current = true;
    setHymnLanguageState(lang);
    AsyncStorage.setItem(HYMN_LANGUAGE_STORAGE_KEY, lang).catch(() => {});
  }, []);

  return (
    <LanguageContext.Provider
      value={{ language, hymnLanguage, t: strings[language], setLanguage, setHymnLanguage }}
    >
      {children}
    </LanguageContext.Provider>
  );
}

export const useLanguage = () => useContext(LanguageContext);
