const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const engine=require('../docs/js/search-engine');
const ctx={window:{}};vm.runInNewContext(fs.readFileSync(require('node:path').join(__dirname,'../docs/data/hymns-data.js'),'utf8'),ctx);
const data=ctx.window.HYMNS_DB.hymns,search=engine.create(data);
assert.equal(search('he aqui')[0].hymn.id,'1');
assert.equal(search('HE AQUÍ!!!')[0].hymn.id,'1');
assert.equal(search('he   aqui')[0].hymn.id,'1');
assert.equal(search('himno 001')[0].hymn.id,'1');
assert.equal(search('#1')[0].hymn.id,'1');
assert.equal(search('E124')[0].hymn.id,'E124');
assert.equal(search('estribillo 124')[0].hymn.id,'E124');
assert.equal(search('he aqui hermso')[0].hymn.id,'1');
assert.equal(search('he aqui heromso')[0].hymn.id,'1');
assert.equal(search('hermoso aqui')[0].hymn.id,'1');
const line=data.find(h=>h.id==='1').lyrics.split('\n').find(l=>l.includes('Redentor'));
assert(search(line,{field:'lyrics'}).some(r=>r.hymn.id==='1'&&r.snippet));
assert(!search(line,{field:'title'}).some(r=>r.hymn.id==='1'));
assert.equal(search('zzzzqqqqxxxx').length,0);
assert.equal(search('<img src=x onerror=alert(1)>').length,0);
assert.deepEqual(engine.ranges('He Aquí Que Tú Eres Hermoso','aqui'),[[3,7]]);
assert(search('10').findIndex(r=>r.hymn.id==='10')<search('10').findIndex(r=>r.hymn.id==='100'));
console.log(`Search checks passed against ${data.length} hymns and choruses.`);
